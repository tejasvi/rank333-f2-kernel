#!/usr/bin/env python3
"""mkF.py CLASS [B]: the lookup module G2.C<CLASS>X_F (mod/src/G2/): the dispatchers F (blocks) and FW (witness rows)
of G2.Disp, chunk equalities (B elements each, default 8192, each its own declaration) and their joins to
  hF : ∀ k < N, lits.getD k 0 = F k     hFW : ∀ k < N, W.getD k [] = FW k     (G2.Asm2)"""
import sys, re
c = int(sys.argv[1]); B = int(sys.argv[2]) if len(sys.argv) > 2 else 8192
import os
G = os.path.dirname(os.path.abspath(__file__)) + '/'
CX = 'C%dX' % c
N = int(re.search(r'theorem lenT : (\d+) = lits.length', open(G + 'mod/src/G2/%s_N.lean' % CX).read()).group(1))
ch = [(a, min(B, N - a)) for a in range(0, N, B)]
L = ['module', 'public import R22Port.U_d41d8cd98f00', 'public import G2.%s_N' % CX, 'public import G2.Asm2', 'meta import G2.Disp',
     '@[expose] public section', 'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0',
     '/-! # O(log n) lookups for the chain `%s` (G2.Disp, G2.Asm2): `F k = lits.getD k 0` and `FW k = W.getD k []` for' % CX,
     '`k < %d`, from %d chunk equalities of at most %d elements (generated by g2/mkF.py) -/' % (N, len(ch), B),
     '#g2f G2.%s %d' % (CX, N), '#g2fw G2.%s "data/%s_W.bin"' % (CX, CX), 'namespace G2.%s' % CX, 'open E1S']
for j, (a, m) in enumerate(ch):
    L.append('theorem eqF%d : G2A.eqL ((lits.drop %d).take %d) (G2A.gen F %d %d) = true := by decide +kernel' % (j, a, m, m, a))
    L.append('theorem eqFW%d : G2A.eqLL ((W.drop %d).take %d) (G2A.genW FW %d %d) = true := by decide +kernel' % (j, a, m, m, a))
for X, eq, lem, join, rhs in (('F', 'eqF', 'getD_of_chunk', 'getD_join', 'lits.getD k 0 = F k'),
                              ('FW', 'eqFW', 'getDW_of_chunk', 'getDW_join', 'W.getD k [] = FW k')):
    for j, (a, m) in enumerate(ch):
        st = 'theorem r%s%d : ∀ k, 0 ≤ k → k < %d → %s :=' % (X, j, a + m, rhs)
        if j == 0: L.append(st + ' fun k h0 h1 => G2A.%s %s0 k h0 h1' % (lem, eq))
        else: L.append(st + ' G2A.%s r%s%d (fun k h0 h1 => G2A.%s %s%d k h0 h1)' % (join, X, j - 1, lem, eq, j))
    L.append('theorem h%s : ∀ k < %d, %s := fun k hk => r%s%d k (Nat.zero_le k) hk' % (X, N, rhs, X, len(ch) - 1))
L += ['end G2.%s' % CX, '']
open(G + 'mod/src/G2/%s_F.lean' % CX, 'w').write('\n'.join(L))
print(CX, 'N', N, 'chunks', len(ch))
