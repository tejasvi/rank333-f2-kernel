#!/usr/bin/env python3
"""mkcap.py: src/R22K/Cap.lean from the frozen port's R22B/CapLeaf2.lean (the port is read-only; this is a renamed copy).

Changes, nothing else:
* namespace R22B.CapLeaf2 -> R22K.Cap; the HCap.C<c>.R22BJobs abbrevs are dropped (they stay CapLeaf2's);
* hCap's hypotheses: the native CovG facts g303 / g321 become the kernel crowns' statements cr303 / cr321 (`G2.Crown303.crown`,
  `G2.Crown321.crown`: `E1NR1.Crown<c>.crown g<c>` with the CovG binder dropped), and each raise class's jobs fact j<c> becomes
  the class certificate k<c> : HC.RRAll -> (∀ p ∈ HC.T_h<c>.RL, HC.ClassLB p.1 p.2) -> HC.ClassLB c lb
  (`fun hrr hcert => KC.h<c>.classLB hrr hcert x<c>`, or `HCap.C<c>.classLB hrr hcert KC.h<c>.jobs`);
* imports: R1.Crown303 / R1.Crown321 (native crowns) dropped; HC.Pad, RT.Cls_e303 / RT.Cls_e321 and E1.IP_e303 / E1.IP_e321
  imported for the crown statements;
* KMod form: the proof is the private theorem `main`, published by `#k1top R22K.Cap.hCap [main]` (KPUB, KAX, KAXSUM, KAXP lines);
* for the HCAPK classes, `public import HCap.C<c>` becomes `public import
  HCapK.C<c>` (the HCapK build, its own LEAN_PATH root): their class roots KC.h<c>.* are built against
  HCapK, whose R<c>* modules re-declare the port's E1G.R<c>.* / E1G.R<c>_WT.*, so the port's HCap.C<c> (and its HCap.R<c>*)
  must not be in the final closure. HCapK.C<c> has the port's HCap.C<c> statements (Cap builds unchanged otherwise) and
  imports the port's HCap.OK_h<c> / HCap.Cls_h<c> / HCap.Sound itself (shared, no clash)."""
import re, sys, os
P = os.path.join(os.environ['PORT_SRC'], 'R22B/CapLeaf2.lean')      # PORT_SRC: the frozen port's source tree
OUT = os.path.join(os.environ.get('FINAL_DIR', os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src/R22K/Cap.lean')
HCAPK_DIR = os.path.join(os.environ['HCAPK_BUILD'], 'HCapK')         # HCAPK_BUILD: the HCapK build (lean/hcapk)
HCAPK = ['454', '456', '465', '469', '471', '472', '473', '476', '485', '487', '490']
have = sorted(f[1:-6] for f in os.listdir(HCAPK_DIR) if re.fullmatch(r'C\d+\.olean', f))
assert have == sorted(HCAPK), ('the HCapK build has C<c> for %s, mkcap.py expects %s: update HCAPK' % (have, HCAPK))
src = open(P).read().split('\n')
out = []; i = 0; skip_ns = False
classes = []
for l in src:
    if l.startswith('public import R1.Crown303') or l.startswith('public import R1.Crown321'):
        continue
    mk = re.fullmatch(r'public import HCap\.C(\d+)', l)
    if mk and mk.group(1) in HCAPK:
        l = 'public import HCapK.C%s' % mk.group(1)
    out.append(l)
assert sum(1 for l in out if re.fullmatch(r'public import HCapK\.C\d+', l)) == len(HCAPK), 'not every HCAPK class import was found'
text = '\n'.join(out)
# drop the R22BJobs namespace blocks
text = re.sub(r'namespace HCap\.C(\d+)\nopen [^\n]*\n/-- the jobs\' coverage[^\n]*\nabbrev R22BJobs : Prop := [^\n]*\nend HCap\.C\d+\n', '', text)
assert 'R22BJobs : Prop' not in text, 'R22BJobs blocks left'
# the header comment
text = text.replace('/-! # R22B.Cap: the class certificates `hCap` of `final_generic`, assembled from hcls\'s route table (generated by lib/py/mkcap.py)',
    '/-! # R22K.Cap: R22B.CapLeaf2 (port, read-only) renamed for the kernel-only final top (s443/ftop/py/mkcap.py): the native CovG facts\n'
    'of classes 303 / 321 replaced by the kernel crowns\' statements (G2.Crown303 / G2.Crown321), each raise class\'s jobs fact by its class\n'
    'certificate (the class certificate KC.h<c>.classLB with its external leaves discharged). Below: CapLeaf2\'s own description.\n\n'
    'R22B.Cap: the class certificates `hCap` of `final_generic`, assembled from the route table (generated by lib/py/mkcap.py)')
# imports for the crown statements
text = text.replace('public import HC.TablesLeafNative\n', 'public import HC.TablesLeafNative\npublic import HC.Pad\npublic import E1.IP_e303\npublic import E1.IP_e321\npublic import RT.Cls_e303\npublic import RT.Cls_e321\nmeta import KMod.Audit\n')
text = text.replace('namespace R22B.CapLeaf2', 'set_option linter.unusedVariables false\nset_option Elab.async false\nnamespace R22K.Cap').replace('end R22B.CapLeaf2', '#k1top R22K.Cap.hCap [main]\nend R22K.Cap').replace('#print axioms R22B.CapLeaf2.hCap\n', '')
# the signature
m = re.search(r'theorem hCap  \(g303 : [^\n]*?\) \(g321 : [^\n]*?\) ((?:\(j\d+ : HCap\.C\d+\.R22BJobs\) ?)+):\n', text)
assert m, 'hCap signature not found'
js = re.findall(r'\(j(\d+) : HCap\.C\d+\.R22BJobs\)', m.group(1))
lbs = {}
for c in js:
    mm = re.search(r'have c%s : HC\.ClassLB %s (\d+) := HCap\.C%s\.classLB HC\.rr_all (\(R22N\.allL_mem \(P := fun p : ℕ × ℕ => HC\.ClassLB p\.1 p\.2\) \(l := HC\.T_h%s\.RL\) [^\n]*?\)) j%s\n' % (c, c, c, c, c), text)
    assert mm, c
    lbs[c] = mm.group(1)
    text = text.replace(mm.group(0), 'have c%s : HC.ClassLB %s %s := k%s HC.rr_all %s\n' % (c, c, mm.group(1), c, mm.group(2)))
crown = lambda c: ('(cr%s : ∀ (hcls : ∀ c, RT.Fact (RT.kM RT.Cls_e%s.CL c) (RT.cLB RT.Cls_e%s.CL c)), HC.E1Concl E1.IP_e%s.Em 18)' % (c, c, c, c))
ks = ' '.join('(k%s : HC.RRAll → (∀ p ∈ HC.T_h%s.RL, HC.ClassLB p.1 p.2) → HC.ClassLB %s %s)' % (c, c, c, lbs[c]) for c in js)
text = text.replace(m.group(0), 'private theorem main %s %s\n    %s :\n' % (crown('303'), crown('321'), ks))
for c in ('303', '321'):
    old = 'E1NR1.Crown%s.crown g%s ' % (c, c)
    assert text.count(old) == 1, (c, text.count(old))
    text = text.replace(old, 'cr%s ' % c)
assert ' g303' not in text and ' g321' not in text and 'R22BJobs' not in text and 'E1NR1' not in text
open(OUT, 'w').write(text)
print('wrote', OUT, 'classes', js, 'lbs', lbs)
