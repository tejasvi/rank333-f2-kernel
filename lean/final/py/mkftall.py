#!/usr/bin/env python3
"""mkftall.py: src/R22K/FinalAll.lean and src/R22K/Cor.lean.

R22K.FinalAll.rank_ge_23_of: `R22K.FinalTop.rank_ge_23` with `hCap := R22K.Cap.hCap …` (classes) and `hrr := HC.rr_all`. Its hypotheses
are the tiers' published root statements: those of R22K.FinalTop other than hCap / hrr, plus the two crowns (`G2.Crown303.crown`,
`G2.Crown321.crown`) and, per raise class c of R22K.Cap, the class root `KC.h<c>.classLB` over its external-leaf list
`KC.h<c>.EXT` (`e<c>`) and `x<c>` (`NDX.h<c>.x<c>`; `fun _ h => absurd h (List.not_mem_nil _)`-style for an empty list).
R22K.Cor: the corollaries R22B.Cor.* of `Top.RankGe23` (as R22B.FinalTop states them).
KMod form: each public theorem is a private theorem published by `#k1top` (KPUB, KAX, KAXSUM, KAXP lines)."""
import re, os
S = os.path.join(os.environ.get('FINAL_DIR', os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src/R22K/')
cap = open(S + 'Cap.lean').read()
ks = re.findall(r'\(k(\d+) : HC\.RRAll → \(∀ p ∈ HC\.T_h\d+\.RL, HC\.ClassLB p\.1 p\.2\) → HC\.ClassLB \d+ (\d+)\)', cap)
assert len(ks) == 21, ks
ft = open(S + 'FinalTop.lean').read()
m = re.search(r'private theorem main\n(.*?) :\n    RankGe23 := by', ft, re.S)
binders = m.group(1)
# drop hrr and hCap from FinalTop's binders (FinalAll supplies them)
b2 = binders.replace('    (hrr : HC.RRAll)\n', '').replace('    (hCap : ∀ p ∈ HC.T_K3eD_Cls.RL, p.1 ≠ 492 → HC.ClassLB p.1 p.2)\n', '')
assert '(hrr' not in b2 and '(hCap' not in b2
def top_binders(t):
    out = []; d = 0; i = 0
    while i < len(t):
        ch = t[i]
        if ch == '-' and t[i:i+2] == '--':
            j = t.find('\n', i); i = len(t) if j < 0 else j; continue
        if ch == '(':
            if d == 0:
                mm = re.match(r'\((\w+) :', t[i:])
                if mm: out.append(mm.group(1))
            d += 1
        elif ch == ')': d -= 1
        i += 1
    return out
names = top_binders(binders)
args = ' '.join(n if n not in ('hrr', 'hCap') else ('HC.rr_all' if n == 'hrr' else 'hcap') for n in names)
nd = lambda c: ('S5.NoDecomp (S5.leafT (E1G.leafRec E1G.IP_h{c}.R E1G.IP_h{c}.VT E1G.IP_h{c}.DOM pl 0)) '
                '(S5.leafN (E1G.leafRec E1G.IP_h{c}.R E1G.IP_h{c}.VT E1G.IP_h{c}.DOM pl 0)) '
                '(S6.leafDom6 (E1G.leafRec E1G.IP_h{c}.R E1G.IP_h{c}.VT E1G.IP_h{c}.DOM pl 0))').format(c=c)
cls = []
for c, lb in ks:
    cls.append('    (e%s : List ℕ)\n    (kc%s : ∀ (hrr : HC.RRAll) (hcert : ∀ p ∈ HC.T_h%s.RL, HC.ClassLB p.1 p.2)\n'
               '      (hext : ∀ pl ∈ e%s, %s), HC.ClassLB %s %s)\n    (x%s : ∀ pl ∈ e%s, %s)\n' % (c, c, c, c, nd(c), c, lb, c, c, nd(c)))
crowns = ('    -- the kernel crowns of classes 303 / 321 (`G2.Crown303.crown`, `G2.Crown321.crown`; lean/cc/g2)\n'
          '    (cr303 : ∀ (hcls : ∀ c, RT.Fact (RT.kM RT.Cls_e303.CL c) (RT.cLB RT.Cls_e303.CL c)), HC.E1Concl E1.IP_e303.Em 18)\n'
          '    (cr321 : ∀ (hcls : ∀ c, RT.Fact (RT.kM RT.Cls_e321.CL c) (RT.cLB RT.Cls_e321.CL c)), HC.E1Concl E1.IP_e321.Em 18)\n')
capargs = ' '.join('(fun hrr hcert => kc%s hrr hcert x%s)' % (c, c) for c, _ in ks)
L = ['module', 'public import R22Port.U_d41d8cd98f00', 'public import R22K.FinalTop', 'public import R22K.Cap',
     'public import S5.Leaf', 'public import S6.Leaf6'] + ['public import HCap.IP_h%s' % c for c, _ in ks] + ['meta import KMod.Audit'] + [
     '/-! # R22K.FinalAll: the kernel-only final theorem with the capacity table assembled (generated by s443/ftop/py/mkftall.py)',
     '',
     '`rank_ge_23_of`: `R22K.FinalTop.rank_ge_23` with `hrr := HC.rr_all` and `hCap := R22K.Cap.hCap cr303 cr321 (k<c> …)`, each raise class',
     'c''s certificate `fun hrr hcert => kc<c> hrr hcert x<c>`: the class certificates `KC.h<c>.classLB` with their external leaves `KC.h<c>.EXT`',
     'refuted by the EXT tops `NDX.h<c>.x<c>` (`e<c>` is that list). Every hypothesis is a published root statement. -/',
     'set_option Elab.async false', '@[expose] public section', 'noncomputable section', 'set_option linter.unusedVariables false', 'namespace R22K.FinalAll', 'open Top R3RT.SpecO', '',
     '/-- a class without external leaves (`KC.h<c>.EXT` is `[]`): its `x<c>` -/',
     'private theorem xNil {P : ℕ → Prop} : ∀ pl ∈ ([] : List ℕ), P pl := fun _ h => absurd h (List.not_mem_nil)',
     '#k1top R22K.FinalAll.x_nil [xNil]', '',
     'private theorem main', crowns + ''.join(cls) + b2.rstrip('\n') + ' :', '    RankGe23 := by',
     '  have hcap := R22K.Cap.hCap cr303 cr321 ' + capargs,
     '  exact R22K.FinalTop.rank_ge_23 ' + args, '', '#k1top R22K.FinalAll.rank_ge_23_of [main]', '', 'end R22K.FinalAll', 'end', '']
open(S + 'FinalAll.lean', 'w').write('\n'.join(L))
C = ['module', 'public import R22Port.U_d41d8cd98f00', 'public import R22B.Corollaries', 'meta import KMod.Audit',
     '/-! # R22K.Cor: the corollaries of `Top.RankGe23` for the final file (R22B.Cor.*, as R22B.FinalTop states them) -/',
     'set_option Elab.async false', '@[expose] public section', 'open FullTable FullTable.WangLadder RootSound Matrix', 'namespace R22K.Cor',
     '/-- with Laderman\'s decomposition: the F2-rank is exactly 23 -/',
     'private theorem rankEq23 (h : Top.RankGe23) :',
     '    (∃ (a b c : Fin 23 → M3), IsDecomp a b c) ∧ ∀ (n : ℕ) (a b c : Fin n → M3), IsDecomp a b c → 23 ≤ n :=',
     '  R22B.Cor.rank_eq_23 h',
     '/-- the matrix-product convention (`C = AB`) -/',
     'private theorem mmEquiv (h : Top.RankGe23) : ∀ (n : ℕ) (a b c : Fin n → M3), R22B.Cor.IsDecompMM a b c → 23 ≤ n :=',
     '  R22B.Cor.mm_equiv.mp h',
     '/-- Rudich-Rousseau\'s table statement at 23 for element 495 -/',
     'private theorem table23 (h : Top.RankGe23) : TableAtLeast ((table[495]!).map mask_matrix) 23 := R22B.Cor.table_23 h',
     '/-- Rudich-Rousseau\'s crown at 23 -/',
     'private theorem recursive23 (h : Top.RankGe23) : RecursiveAlgorithmMultiplicationsAtLeast 23 := R22B.Cor.recursive_23 h',
     '#k1top R22K.Cor.rank_eq_23 [rankEq23]', '#k1top R22K.Cor.mm_equiv [mmEquiv]', '#k1top R22K.Cor.table_23 [table23]',
     '#k1top R22K.Cor.recursive_23 [recursive23]', 'end R22K.Cor', '']
open(S + 'Cor.lean', 'w').write('\n'.join(C))
print('FinalAll:', len(names) - 2 + 2 + 3 * len(ks), 'hypotheses;', 'classes', [c for c, _ in ks])
