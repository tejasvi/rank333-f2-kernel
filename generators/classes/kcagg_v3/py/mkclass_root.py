"""mkclass_root.py: the class module KC.h<C>_Class of an hcap class-raise class, written by kcagg.py once the class's packages
are done.  Public:
  KC.h<C>.EXT : List ℕ   the class's external leaves (packed prefixes), a literal list (exposed);
  KC.h<C>.jobs : ∀ k < nJ, JobOK (withExt E1G.IP_h<C>.C KC.h<C>.EXT) (E1G.slc E1G.SL_h<C>.chunk) E1G.IP_h<C>.UB (E1G.R<C>_HT.entry k)
      from the class's root range (range_all; a lifted root range is instantiated at KC.h<C>.EXT, its own list being included in
      it by kernel evaluation: E1GK.JobCmd3 makes every NS.EXT a literal list, so the root range's list unfolds);
      for a class without external leaves this is R22B.Cap's `R22BJobs` (withExt C [] = C = Cx EXT);
  KC.h<C>.classLB (hrr) (hcert) (hext : ∀ pl ∈ KC.h<C>.EXT, NoDecomp …) : ClassLB C LB
      the port's HCap.C<C>.classLB with these jobs: the root level E1G.R<C>.root re-proved over withExt C KC.h<C>.EXT (the port's
      okRoot, okGlue, len, UB_eq, UBR_eq; the top chain's blkChk re-decided over that context in 16-block declarations), then
      HCap.e1_sound_enum with ipok KC.h<C>.EXT and hext;
  KC.h<C>.classLB0 (hrr) (hcert) : ClassLB C LB   only when KC.h<C>.EXT = [] (hext discharged)."""
import re, sys
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
try:
    from kcgen import K   # the E1G library kjlib.py (package mode: set_package) as used by kcagg.py
except ImportError:
    raise
HCAPK_CR = {'456', '472', '473', '476', '485', '487', '490', '454', '465', '469', '471'}
# class -> (LB: `cLB K3eD_Cls.CL c`, L: the root level's top-chain length `E1G.R<c>.lits.length`), read once from the port sources
CLASSDATA = {'420': (20, 7), '450': (20, 38), '451': (20, 25), '454': (20, 188), '455': (20, 113), '456': (20, 76), '458': (20, 34), '460': (20, 4),
             '463': (20, 9), '464': (20, 49), '465': (20, 36), '469': (20, 24), '470': (20, 45), '471': (20, 44), '472': (20, 36), '473': (20, 73),
             '475': (20, 24), '476': (20, 61), '485': (21, 77), '487': (21, 339), '490': (21, 191)}

def write(c, root_child, root_mod, lifted, ext, man):
    ctx = 'h' + c; E = K.EMIT[ctx]; nJ = E['nJ']
    LB, L = CLASSDATA[c]   # from the port's HCap/C<c>.lean (lbK) and HCap/R<c>.lean (len); a table, so the generator needs no port sources
    rootThm = root_child                              # e.g. KC.h460_A.ok (or KC.h460.L0.ok)
    rootNS = rootThm[:-len('.ok')]
    isl = root_mod in lifted
    C = 'E1G.IP_%s.C' % ctx; Cp = '(E1GS.withExt %s KC.%s.EXT)' % (C, ctx); SL = '(E1G.slc E1G.SL_%s.chunk)' % ctx
    UB, UBR = 'E1G.IP_%s.UB' % ctx, 'E1G.IP_%s.UBR' % ctx
    R = 'E1G.R%s' % c
    HK = 'HCapK' if c in HCAPK_CR else 'HCap'   # 11 classes build on the HCapK copies of their C/R modules (7 of them also on OK/R_HT)
    out = ['module', 'public import %s.C%s' % (HK, c), 'public import %s.R%s' % (HK, c), 'public import E1GK.ExtMono',
           'import E1GK.ChainF', 'import %s' % root_mod] + [
           'meta import KMod.Units', 'meta import KMod.Audit',
           'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', 'set_option Elab.async false',
           '/-! # Class %s: `ClassLB %s %d` from the KC job modules (generated by leaf2/kc/py/mkclass_root.py)' % (c, c, LB), '',
           'The root range `%s` covers the %d root jobs of the port\'s table `E1G.R%s_HT`%s.  The root level `%s` (top chain of %d' % (
               rootThm, nJ, c, ' (lifted over its external leaves)' if isl else '', R, L),
           'blocks glued to the jobs) is re-proved over `withExt C KC.%s.EXT`, which is the port\'s `E1G.OK_%s.Cx KC.%s.EXT`. -/' % (ctx, ctx, ctx),
           'namespace KC.%s' % ctx,
           '/-- the external leaves of class %s (packed prefixes `Σ l_i 2^(7 i)`, job order; %d leaves) -/' % (c, len(ext)),
           '@[expose] public def EXT : List ℕ := [%s]' % ', '.join(map(str, ext)),
           'end KC.%s' % ctx, '', 'namespace KC.%s' % ctx, 'open E1GS RT HC E1G.IP_%s E1G.OK_%s' % (ctx, ctx)]
    if isl:
        # the inclusion of the root range's list in the class's list, decided by the kernel with a direct `List.rec` membership test
        # (v3: `E1GS.subset_of_all`'s `List.all`/`List.elem` evaluation took 52 s at 295 leaves and 7167 s at 1196; this takes 2.9 s at 295)
        out += ['/-- membership by direct `List.rec`: one `Nat.beq` and one `or` per element -/',
                'private def memN (p : ℕ) (l : List ℕ) : Bool := List.rec (motive := fun _ => Bool) false (fun x _ r => Nat.beq p x || r) l',
                'private def allMemN (e : List ℕ) (L : List ℕ) : Bool := List.rec (motive := fun _ => Bool) true (fun x _ r => memN x e && r) L',
                'private theorem memN_mem (p : ℕ) : ∀ l : List ℕ, memN p l = true → p ∈ l',
                '  | [], h => by cases h',
                '  | x :: t, h => by',
                '    have h\' : (Nat.beq p x || memN p t) = true := h',
                '    rcases Bool.or_eq_true_iff.mp h\' with h1 | h1',
                '    · rw [Nat.eq_of_beq_eq_true h1]; exact List.mem_cons_self',
                '    · exact List.mem_cons_of_mem _ (memN_mem p t h1)',
                'private theorem allMemN_sub (e : List ℕ) : ∀ L : List ℕ, allMemN e L = true → E1GS.ExtSub L e',
                '  | [], _ => E1GS.extSub_nil e',
                '  | x :: t, h => by',
                '    have h\' : (memN x e && allMemN e t) = true := h',
                '    rcases Bool.and_eq_true_iff.mp h\' with ⟨h1, h2⟩',
                '    intro q hq',
                '    rcases List.mem_cons.mp hq with rfl | hq\'',
                '    · exact memN_mem q e h1',
                '    · exact allMemN_sub e t h2 q hq\'',
                'private theorem extSub : E1GS.ExtSub %s.EXT KC.%s.EXT := allMemN_sub _ _ (by decide +kernel)' % (rootNS, ctx),
                '#kpubterm KC.%s.jobs : ∀ k < %d, E1GS.JobOK %s %s %s (E1G.R%s_HT.entry k) :=' % (ctx, nJ, Cp, SL, UB, c),
                '  E1GS.range_all _ %d (%s KC.%s.EXT extSub)' % (nJ, rootThm, ctx)]
    else:
        out += ['#kpubterm KC.%s.jobs : ∀ k < %d, E1GS.JobOK %s %s %s (E1G.R%s_HT.entry k) :=' % (ctx, nJ, Cp, SL, UB, c),
                '  E1GS.range_all _ %d %s' % (nJ, rootThm)]
    # the top chain over C', in 16-block declarations, joined
    chunks = [(a, min(16, L - a)) for a in range(0, L, 16)]
    for j, (a, m) in enumerate(chunks):
        out.append('private theorem okB%d : E1GS.blkChk %s %s %s %s %s.lits %d %d = true := by decide +kernel' % (j, Cp, SL, UB, UBR, R, a, m))
    out.append('private theorem okAll : E1GS.blkChk %s %s %s %s %s.lits 0 %d = true := by' % (Cp, SL, UB, UBR, R, L))
    acc = 'okB0'; tot = chunks[0][1]
    for j, (a, m) in enumerate(chunks[1:], 1):
        out.append('  have h%d : E1GS.blkChk %s %s %s %s %s.lits 0 %d = true := E1GS.blkChk_join _ _ _ _ _ 0 %d %d %s okB%d' % (
            j, Cp, SL, UB, UBR, R, tot + m, tot, m, acc, j))
        acc = 'h%d' % j; tot += m
    out.append('  exact %s' % acc)
    out += ['private theorem root : ∀ x : ℕ → ℕ, Glob %s x → (∀ i < 2 ^ 15, SlotV x (%s i)) → (∀ l < 127, x l ≤ E1G.fld UB l) →' % (Cp, SL),
            '    (∃ l < 127, 0 < x l) → False :=',
            '  enum_of_chain_w %s %s UB UBR %s.UB_eq %s.UBR_eq (by decide +kernel) %s.lits %d E1G.R%s_HT.entry E1G.R%s_Wf (by rw [%s.len]; decide) %s.okRoot' % (
                Cp, SL, R, R, R, nJ, c, c, R, R),
            '    (blkChk_spec _ _ _ _ _ _ (%s.len ▸ okAll)) %s.okGlue KC.%s.jobs' % (R, R, ctx),
            '-- **ClassLB %s %d** from the KC job modules, given the class table\'s certificates and the external leaves\' refutations' % (c, LB),
            '#kpubterm KC.%s.classLB : ∀ (hrr : RRAll) (hcert : ∀ p ∈ T_%s.RL, ClassLB p.1 p.2)' % (ctx, ctx),
            '    (hext : ∀ pl ∈ KC.%s.EXT, S5.NoDecomp (S5.leafT (E1G.leafRec R VT DOM pl 0)) (S5.leafN (E1G.leafRec R VT DOM pl 0))' % ctx,
            '      (S6.leafDom6 (E1G.leafRec R VT DOM pl 0))), ClassLB %s %d :=' % (c, LB),
            '  fun hrr hcert hext => classLB_of_e1 (by decide)',
            '    (HCap.e1_sound_enum (Cx KC.%s.EXT) Em LB LBR UB UBR Ntab nrows sl tab ge (ipok KC.%s.EXT) (HCap.C%s.hrow (T_%s.hcls hrr hcert)) hext root)' % (ctx, ctx, c, ctx),
            '    HCap.C%s.one HCap.C%s.sub' % (c, c)]
    if not ext:
        out += ['-- the same without external leaves (the list is empty)',
                '#kpubterm KC.%s.classLB0 : ∀ (hrr : RRAll) (hcert : ∀ p ∈ T_%s.RL, ClassLB p.1 p.2), ClassLB %s %d :=' % (ctx, ctx, c, LB),
                '  fun hrr hcert => KC.%s.classLB hrr hcert (fun pl h => absurd h List.not_mem_nil)' % ctx]
    out += ['end KC.%s' % ctx, '#kax KC.%s.classLB' % ctx, '#kaxp KC.%s.classLB' % ctx, '#kax KC.%s.jobs' % ctx, '#kaxp KC.%s.jobs' % ctx]
    if not ext: out += ['#kax KC.%s.classLB0' % ctx]
    out += ['#kkey "%s/0" "%s/%d"' % (ctx, ctx, nJ - 1)] + K.kext_lines(ctx, ctx, [])
    mod = 'KC.%s_Class' % ctx
    open(K.MD + '%s_Class.lean' % ctx, 'w').write('\n'.join(out) + '\n')
    K.manifest([{'module': mod, 'tier': ctx, 'kind': 'class', 'lifted': False, 'pred_kernel_s': round(2.0 + 0.3 * L + 3.5e-5 * len(ext) ** 2, 1), 'pred_anon_gb': 1.0,
                 'input_bytes': 0, 'imports': ['%s.C%s' % (HK, c), '%s.R%s' % (HK, c), 'E1GK.ExtMono', root_mod],
                 'pub': ['KC.%s.jobs' % ctx, 'KC.%s.classLB' % ctx] + (['KC.%s.classLB0' % ctx] if not ext else [])}], man)
    return mod
