#!/usr/bin/env python3
"""mkloadcc.py N: writes lean/KB/LoadItemCC_<N>.lean, the kernel track's item loaders on the CC route's table N (py/mkcc.py,
KB.CC_<N>_F): KB.LoadItem / LoadItemR / LoadItemR2's head, packed batches (#kritemB2), end and dead-root loaders with the table
names of N: the records' cap-2 tables `N.c2t_<l>`, the item checker's `N.c2T` and `N.c1`, the job table checked by
`R3RT.tabOKQ (KCC.rowECC N.L)` and stated as `KB.TabVCC N.L` (KB.CCDefs).  Commands: #kritemHeadCC, #kritemB2CC, #kritemEndCC,
#kditemDeadCC.
Root frames use KB.PcB's fast checks: the loader evaluates `KB.rootChk0F` / `KB.rootChkWF` (byte popcounts) and states `KB.rootChk0` /
`KB.rootChkW` through `KB.rootChk0F_imp` / `KB.rootChkWF_imp` (no evaluation), so the item predicates are unchanged.
Import base : the loader imports neither KB.CC_<N>_F nor anything else of the table's closure, and KB.PcB data-only
(`-- nometa`); every constant is named by an unchecked literal `X (the item module, which imports KB.CC_<N>_F, resolves them when it
adds the items' declarations). An item module that meta-imports the loader then loads only the loader helpers' IR, not the IR of the
whole Mathlib / table closure (item units' import base 1.62 -> 0.60 GB RssAnon)."""
import os
import re, sys
K = os.environ.get('KINDS_R22', '.') + '/lean/kinds/lean'
N = sys.argv[1]
src = {f: open('%s/KB/%s.lean' % (K, f)).read() for f in ('LoadItem', 'LoadItemR', 'LoadItemR2')}
def grab(f, name):
    s = src[f]
    m = re.search(r'(^/--(?:(?!-/).)*-/\n)?^(partial )?def %s\b' % re.escape(name), s, re.M | re.S)
    if not m: raise SystemExit('no def %s in %s' % (name, f))
    st = m.start()
    nxt = re.compile(r'^(/--|def |partial def |elab |theorem |end |namespace |open |structure )', re.M)
    m2 = nxt.search(s, m.end())
    return s[st:m2.start() if m2 else len(s)].rstrip() + '\n'
funcs = [('LoadItem', 'dkPair'), ('LoadItem', 'parseDK'), ('LoadItem', 'parseExt'), ('LoadItem', 'itemTable'), ('LoadItem', 'itemHead'),
         ('LoadItem', 'itemDead'), ('LoadItemR', 'parseExtR'), ('LoadItemR', 'extRE'), ('LoadItemR', 'chainArgsR'), ('LoadItemR', 'itemHeadR'),
         ('LoadItemR', 'itemEndR'), ('LoadItemR2', 'parseRec2'), ('LoadItemR2', 'itemBatchesR2')]
names = [n for _, n in funcs]
body = ''
for f, n in funcs: body += grab(f, n) + '\n'
# rename the copied functions (longest names first) and their calls
for n in sorted(names, key=len, reverse=True):
    body = re.sub(r'\b%s\b(?!CC)' % re.escape(n), n + 'CC', body)
# table names of N
body = body.replace('mkConst (tabName ', 'mkConst (ccTabN ').replace('KDLoadXB.litOf (tabName ', 'KDLoadXB.litOf (ccTabN ')
body = body.replace('mkConst `KI.c2T', 'mkConst (NS ++ `c2T)').replace('mkConst `KI.c1', 'mkConst (NS ++ `c1)')
body = body.replace('mkConst ``L5II.rowEII', '(mkApp (mkConst ``KCC.rowECC) (mkConst (NS ++ `L)))')
body = body.replace('(mkApp (mkConst ``KB.TabVII) tab)', '(mkApp2 (mkConst ``KB.TabVCC) (mkConst (NS ++ `L)) tab)')
body = body.replace('(mkAppN (mkConst ``KB.tabVII_of) #[chunkE,', '(mkAppN (mkConst ``KB.tabVCC_of) #[mkConst (NS ++ `L), chunkE,')
# root frames: KB.PcB's fast checks, evaluated; the stated facts follow by the _imp lemmas (the design notes: 44 ms per witness row before)
RA = '''#[mkConst (NS ++ `c1), mkConst (NS ++ `c2T), mkConst `KI.hkT, tab,
    mkConst (I ++ `pl), mkConst (I ++ `W), mkConst (I ++ `lastP), mkConst (I ++ `f0)]'''
for chk, nm in (('rootChkW', 'rootc'), ('rootChk0', 'root')):
    old = '''  let wr ← thm (I ++ `%s) (eqTrue (mkAppN (mkConst ``KB.%s) %s)) rflTrue s!"{I} root frame"''' % (nm, chk, RA)
    new = ('''  -- the root frame: the fast check (byte popcounts, KB.PcB) is evaluated; KB.%s follows by KB.%sF_imp (no evaluation)
  let rfA := %s
  let wr ← thm (I ++ `%sF) (eqTrue (mkAppN (mkConst ``KB.%sF) rfA)) rflTrue s!"{I} root frame"
  let _ ← thm (I ++ `%s) (eqTrue (mkAppN (mkConst ``KB.%s) rfA))
    (mkAppN (mkConst ``KB.%sF_imp) (rfA.push (mkConst (I ++ `%sF)))) s!"{I} root frame ({chk})"''' % (chk, chk, RA, nm, chk, nm, chk, chk, nm)).replace('{chk}', chk)
    assert body.count(old) == 1, (chk, body.count(old))
    body = body.replace(old, new)
assert 'tabName' not in body and '`KI.c2T' not in body and '`KI.c1' not in body and 'rowEII' not in body and 'TabVII' not in body, \
    [l for l in body.split('\n') if 'tabName' in l or 'KI.c2T' in l or 'KI.c1' in l or 'rowEII' in l or 'TabVII' in l][:5]
hdr = '''import KB.LoadItemR2
import KB.PcB -- nometa
/-! # KB.LoadItemCC_%(N)s: the kernel track's item loaders on the CC route's table `%(N)s` (generated by py/mkloadcc.py)

As `#kritemHead`, `#kritemB2`, `#kritemEnd`, `#kditemDead` (KB.LoadItem, LoadItemR, LoadItemR2), with the table names of
`KCC_%(N)s`: the records' cap-2 tables `KCC_%(N)s.c2t_<l>`, the item checker's `KCC_%(N)s.c2T` and `KCC_%(N)s.c1`, the job table
checked by `R3RT.tabOKQ (KCC.rowECC KCC_%(N)s.L)` and stated as `KB.TabVCC KCC_%(N)s.L`.  An item then gives
`KB.CheckedRCC_%(N)s` (or `KB.CheckedDeadCC_%(N)s`) and its segment by `KB.segRefAllRCC_%(N)s`. -/
open Lean Elab Command L1Load KBLoad KBLoadR KBLoadR2
namespace KBLoadCC_%(N)s

def NS : Name := `KCC_%(N)s
def ccTabN (l : Nat) : Name := NS ++ Name.mkSimple s!"c2t_{l}"

''' % dict(N=N)
tail = '''elab "#kritemHeadCC " id:ident p:str key:num : command => itemHeadRCC id.getId p.getString key.getNat
elab "#kritemB2CC " id:ident p:str k0:num k1:num : command => do
  let w ← itemBatchesR2CC id.getId p.getString k0.getNat k1.getNat
  logInfo m!"{id.getId}: batches {k0.getNat}..{k1.getNat} (packed, CC): kernel {w} ms"
elab "#kritemEndCC " id:ident : command => itemEndRCC id.getId
elab "#kditemDeadCC " id:ident p:str key:num : command => itemDeadCC id.getId p.getString key.getNat
end KBLoadCC_%(N)s
''' % dict(N=N)
open('%s/KB/LoadItemCC_%s.lean' % (K, N), 'w').write(re.sub(r'``(?=[A-Za-z_])', '`', hdr + body + tail))   # unchecked names (see above)
print('wrote KB/LoadItemCC_%s.lean: %d functions' % (N, len(funcs)))
