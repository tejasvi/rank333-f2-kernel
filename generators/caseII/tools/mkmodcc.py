#!/usr/bin/env python3
"""mkmodcc.py N: writes lean/KB/ModItemCC_<N>.lean (non-module source; kinds/mod/tomod.py ports it): the module-form item emitter
on the CC route's table N.  The loaders of KB.LoadItemCC_<N> (py/mkloadcc.py) with
* every item name private (`mkPrivateName`): the item's table, records, stacks, batch checks, chain and facts land in the module's
  .olean.private;
* every theorem added by `addDecl` (module-aware), not `Environment.addDeclCore`;
commands `#kmHead I "dir" key`, `#kmB I "dir" k0 k1`, `#kmEnd I`, `#kmDead I "dir" key` (as #kritemHeadCC …), and
`#kmKeys thm I1 I2 …` (logged as KPUB by `KMod.addPub`, plan 7a): the module's one public theorem `thm : R22N.KeysOK checked [key1, key2, …]` with
`checked k := KB.CheckedRCC_<N> k ∨ KB.CheckedDeadCC_<N> k`, from the items' private theorems `Ij.checked` (`Or.inl` for an OPEN
root, `Or.inr` for a dead one, as `Ij.dead` exists).  Every constant is named by an unchecked literal `X, as in py/mkloadcc.py (the
module imports nothing of the table's closure; the design notes)."""
import os
import re, sys
K = os.environ.get('KINDS_R22', '.') + '/lean/kinds/lean'
N = sys.argv[1]
s = open('%s/KB/LoadItemCC_%s.lean' % (K, N)).read()
i = s.index('def NS : Name'); j = s.index('elab "#kritemHeadCC "')
body = s[i:j]
for fn in ['dkPairCC', 'parseDKCC', 'parseExtCC', 'itemTableCC', 'itemHeadCC', 'itemDeadCC', 'parseExtRCC', 'extRECC', 'chainArgsRCC',
           'itemHeadRCC', 'itemEndRCC', 'parseRec2CC', 'itemBatchesR2CC']:
    body = re.sub(r'\b%s\b' % fn, fn[:-2] + 'CM', body)
body = re.sub(r'(?<![\w.])thm \(', 'thmP (', body)
assert 'R3RTAdd.addTimed' not in body
hdr = '''import KB.LoadItemCC_%(N)s
import KMod.Units
/-! # KB.ModItemCC_%(N)s: the module-form item emitter on the CC route's table `%(N)s` (generated by py/mkmodcc.py)

The loaders of `KB.LoadItemCC_%(N)s` with every item name private (`mkPrivateName`) and every theorem added by `addDecl`, so that an
item module's records, tables, stacks, batch checks and facts stay in its `.olean.private`.  Commands: `#kmHead`, `#kmB`, `#kmEnd`,
`#kmDead` (as `#kritemHeadCC`, `#kritemB2CC`, `#kritemEndCC`, `#kditemDeadCC`, on the private item name), and
`#kmKeys thm I1 I2 …`, the module's one public theorem `thm : R22N.KeysOK checked [key1, …]` (`checked k :=
KB.CheckedRCC_%(N)s k ∨ KB.CheckedDeadCC_%(N)s k`) from the items' private `Ij.checked`. -/
open Lean Elab Command L1Load KBLoad KBLoadR KBLoadR2
namespace KBModCC_%(N)s

/-- a theorem through `addDecl` (module-aware; private names stay private), kernel time in ms -/
def thmP (n : Name) (ty pf : Expr) (what : String) : CommandElabM Nat := do
  let t0 ← IO.monoNanosNow
  try liftCoreM <| addDecl (Declaration.thmDecl { name := n, levelParams := [], type := ty, value := pf })
  catch e => throwError m!"{what}: kernel rejects: {e.toMessageData}"
  let t1 ← IO.monoNanosNow
  return (t1 - t0) / 1000000

''' % dict(N=N)
tail = '''def priv (n : Name) : CommandElabM Name := return mkPrivateName (← getEnv) n

elab "#kmHead " id:ident p:str key:num : command => do itemHeadRCM (← priv id.getId) p.getString key.getNat
elab "#kmB " id:ident p:str k0:num k1:num : command => do
  let w ← itemBatchesR2CM (← priv id.getId) p.getString k0.getNat k1.getNat
  logInfo m!"{id.getId}: batches {k0.getNat}..{k1.getNat}: kernel {w} ms"
elab "#kmEnd " id:ident : command => do itemEndRCM (← priv id.getId)
elab "#kmDead " id:ident p:str key:num : command => do itemDeadCM (← priv id.getId) p.getString key.getNat

/-- the module's checked predicate -/
def checkedE : Expr := mkLambda `k BinderInfo.default natTy
  (mkApp2 (mkConst ``Or) (mkApp (mkConst ``KB.CheckedRCC_%(N)s) (mkBVar 0)) (mkApp (mkConst ``KB.CheckedDeadCC_%(N)s) (mkBVar 0)))

elab "#kmKeys " t:ident ids:ident* : command => do
  let env ← getEnv
  let mut keys : Array Nat := #[]
  let mut pfs : Array Expr := #[]
  for i in ids do
    let I := mkPrivateName env i.getId
    let k ← KDLoadXB.litOf (I ++ `key)
    keys := keys.push k
    let dead := env.contains (I ++ `dk)
    let ck := mkConst (I ++ `checked)
    pfs := pfs.push (if dead then
        mkApp3 (mkConst ``Or.inr) (mkApp (mkConst ``KB.CheckedRCC_%(N)s) (mkRawNatLit k)) (mkApp (mkConst ``KB.CheckedDeadCC_%(N)s) (mkRawNatLit k)) ck
      else mkApp3 (mkConst ``Or.inl) (mkApp (mkConst ``KB.CheckedRCC_%(N)s) (mkRawNatLit k)) (mkApp (mkConst ``KB.CheckedDeadCC_%(N)s) (mkRawNatLit k)) ck)
  -- KeysOK checked [k…] = AllL checked [k…] = checked k1 ∧ (… ∧ True)
  let P (k : Nat) : Expr := mkApp checkedE (mkRawNatLit k)
  let mut ty := mkConst ``True
  let mut pf := mkConst ``True.intro
  for j in [0:keys.size] do
    let jj := keys.size - 1 - j
    pf := mkApp4 (mkConst ``And.intro) (P keys[jj]!) ty pfs[jj]! pf
    ty := mkApp2 (mkConst ``And) (P keys[jj]!) ty
  let kl := mkList natTy (keys.toList.map mkRawNatLit)
  let stmt := mkApp2 (mkConst ``R22N.KeysOK) checkedE kl
  KMod.addPub t.getId stmt pf
  logInfo m!"{t.getId}: KeysOK over {keys.size} items"
end KBModCC_%(N)s
''' % dict(N=N)
open('%s/KB/ModItemCC_%s.lean' % (K, N), 'w').write(re.sub(r'``(?=[A-Za-z_])', '`', hdr + body + tail))   # unchecked names
print('wrote KB/ModItemCC_%s.lean' % N)
